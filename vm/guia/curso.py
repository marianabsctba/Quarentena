def curso_dict():
    """Estrutura enviada ao front-end (sem as respostas, que ficam no servidor)."""
    casos = []
    for c in CASOS:
        passos = [{"id": p["id"], "titulo": p["titulo"], "tool": p["tool"],
                   "instr": p["instr"], "pergunta": p["pergunta"], "dica": p["dica"]}
                  for p in c["passos"]]
        tools = [dict(TOOLS[tid], id=tid) for tid in c["tools"] if tid in TOOLS]
        casos.append({"id": c["id"], "nome": c["nome"], "nivel": c["nivel"],
                      "arquivo": c["arquivo"], "origem": c["origem"],
                      "tools": tools, "passos": passos})
    return {"intro": INTRO, "casos": casos}


def caso_por_id(caso_id):
    for c in CASOS:
        if c["id"] == caso_id:
            return c
    return None


def achar_passo(caso_id, passo_id):
    c = caso_por_id(caso_id)
    if c:
        for p in c["passos"]:
            if p["id"] == passo_id:
                return p
    return None
